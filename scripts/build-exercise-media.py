#!/usr/bin/env python3
"""Build src/data/exerciseMedia.ts and assets/exercises/ from the RepDB free-tier dataset.

Usage: python3 scripts/build-exercise-media.py <path to RepDB exercises.json>

Download exercises.json from https://github.com/RepDB/exercise-dataset. The Gymple
exercise id -> RepDB id matches live in scripts/repdb-map.json (hand-picked; only
exercises with a faithful match are listed). Images are fetched from the RepDB repo.

RepDB free-tier license: in-app use only, attribution "Exercise data by RepDB
(repdb.co)" required, no redistribution as a dataset. See assets/exercises/LICENSE.md.
"""
import json
import os
import subprocess
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
RAW = 'https://raw.githubusercontent.com/RepDB/exercise-dataset/main/'


def ts_string(value: str) -> str:
    return "'" + value.replace('\\', '\\\\').replace("'", "\\'") + "'"


def main() -> None:
    dataset = {e['id']: e for e in json.load(open(sys.argv[1]))['exercises']}
    mapping = json.load(open(os.path.join(ROOT, 'scripts', 'repdb-map.json')))
    out_dir = os.path.join(ROOT, 'assets', 'exercises')
    os.makedirs(out_dir, exist_ok=True)

    entries = []
    for ours, repdb_id in mapping.items():
        exercise = dataset[repdb_id]
        images = []
        for kind, path in exercise['images']['flat'].items():
            target = os.path.join(out_dir, f'{ours}-{kind}.webp')
            if not os.path.exists(target):
                subprocess.run(['curl', '-sSf', '-o', target, RAW + path], check=True)
            images.append(f"    {kind}: require('../../assets/exercises/{ours}-{kind}.webp'),")
        steps = ', '.join(ts_string(s) for s in exercise['instructions_en'])
        tips = ', '.join(ts_string(s) for s in exercise.get('tips_en') or [])
        entries.append(
            f'  {ours}: {{\n'
            + '\n'.join(images)
            + f"\n    instructions: [{steps}],\n    tips: [{tips}],\n  }},"
        )

    header = (
        "import type { ImageSourcePropType } from 'react-native';\n\n"
        '// Generated by scripts/build-exercise-media.py from the RepDB free-tier dataset.\n'
        '// Exercise data by RepDB (repdb.co): in-app use only, see assets/exercises/LICENSE.md.\n\n'
        'export interface ExerciseMedia {\n'
        '  start?: ImageSourcePropType;\n'
        '  peak?: ImageSourcePropType;\n'
        '  /** Single pose, for holds such as planks. */\n'
        '  main?: ImageSourcePropType;\n'
        '  instructions: string[];\n'
        '  tips: string[];\n'
        '}\n\n'
        'export const EXERCISE_MEDIA: Partial<Record<string, ExerciseMedia>> = {\n'
    )
    footer = (
        '};\n\n'
        '/** The image that best shows the movement: the peak pose, else the single pose. */\n'
        'export function thumbnailFor(exerciseId: string): ImageSourcePropType | undefined {\n'
        '  const media = EXERCISE_MEDIA[exerciseId];\n'
        '  return media?.peak ?? media?.main ?? media?.start;\n'
        '}\n'
    )
    with open(os.path.join(ROOT, 'src', 'data', 'exerciseMedia.ts'), 'w') as f:
        f.write(header + '\n'.join(entries) + '\n' + footer)
    print(f'{len(entries)} exercises written')


if __name__ == '__main__':
    main()
